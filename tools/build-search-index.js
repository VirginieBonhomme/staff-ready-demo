#!/usr/bin/env node
// Regenerates assets/search-index.js from all HTML content pages.
// Run from project root: node tools/build-search-index.js

const fs   = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT  = path.join(ROOT, 'assets', 'search-index.js');

const SKIP_FILES = new Set([
  'search/index.html',
  'gate-wifi.html',
  'gate-boh.html',
  'index.html',
]);

// ── Category from path ────────────────────────────────────────────────────────
function getCategory(rel) {
  if (rel.startsWith('front-of-house/sops/'))       return 'FOH · SOP';
  if (rel.startsWith('front-of-house/roles/'))      return 'FOH · Role';
  if (rel.startsWith('front-of-house/checklists/')) return 'FOH · Checklist';
  if (rel.startsWith('front-of-house/'))            return 'FOH';
  if (rel.startsWith('back-of-house/checklists/'))  return 'BOH · Checklist';
  if (rel.startsWith('back-of-house/'))             return 'BOH';
  if (rel.startsWith('sops/'))                      return 'SOP';
  if (rel.startsWith('checklists/'))                return 'Checklist';
  if (rel.startsWith('roles/'))                     return 'Role';
  if (rel.startsWith('onboarding/'))                return 'Onboarding';
  if (rel.startsWith('recipes/'))                   return 'Recipe';
  if (rel.startsWith('food-safety/'))               return 'Food Safety';
  if (rel.startsWith('crisis/'))                    return 'Reference';
  return 'General';
}

// ── HTML helpers ──────────────────────────────────────────────────────────────
function stripTags(html) {
  return html
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&[a-z#\d]+;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function first(html, re) {
  const m = html.match(re);
  return m ? stripTags(m[1]).trim() : '';
}

function all(html, re) {
  const out = [];
  const g = new RegExp(re.source, 'gi');
  let m;
  while ((m = g.exec(html)) !== null) {
    const t = stripTags(m[1]).trim();
    if (t) out.push(t);
  }
  return out;
}

// ── Per-file processing ───────────────────────────────────────────────────────
function processFile(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  const rel = path.relative(ROOT, filePath).replace(/\\/g, '/');

  // Strip nav/footer/script/style from main content
  const mainMatch = raw.match(/<main[^>]*>([\s\S]*?)<\/main>/i);
  const mainHtml  = mainMatch ? mainMatch[1] : raw;
  const cleanMain = mainHtml.replace(/<(script|style)[^>]*>[\s\S]*?<\/\1>/gi, '');

  // Title: from <title>, strip site suffix
  const title = first(raw, /<title>([\s\S]*?)<\/title>/i)
    .replace(/\s*[·\-|]\s*Staff Ready Ops\.?$/i, '').trim();

  // Category from path
  const category = getCategory(rel);

  // Excerpt: first meaty paragraph
  const paras = all(cleanMain, /<p[^>]*>([\s\S]*?)<\/p>/i)
    .filter(p => p.length > 30 && !p.startsWith('Staff Ready'));
  const excerpt = paras.length
    ? paras[0].slice(0, 300) + (paras[0].length > 300 ? '…' : '')
    : '';

  // Keywords: path segments + all headings
  const pathParts = rel.replace('.html', '').split('/').map(s => s.replace(/-/g, ' ')).filter(Boolean);
  const h1s = all(cleanMain, /<h1[^>]*>([\s\S]*?)<\/h1>/i);
  const h2s = all(cleanMain, /<h2[^>]*>([\s\S]*?)<\/h2>/i);
  const h3s = all(cleanMain, /<h3[^>]*>([\s\S]*?)<\/h3>/i);
  const keywords = [...new Set(
    [...pathParts, ...h1s, ...h2s, ...h3s].map(k => k.toLowerCase()).filter(k => k.length > 1)
  )];

  // Body: all main text for broad matching (capped at 3000 chars)
  const body = stripTags(cleanMain).slice(0, 3000);

  return { title, url: '../' + rel, category, excerpt, keywords, body };
}

// ── Walk ──────────────────────────────────────────────────────────────────────
const SKIP_DIRS = new Set(['assets', 'tools', '.git', 'node_modules']);

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, entry);
    if (fs.statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(entry)) walk(full, files);
    } else if (entry.endsWith('.html')) {
      files.push(full);
    }
  }
  return files;
}

// ── Main ──────────────────────────────────────────────────────────────────────
const entries = [];
for (const file of walk(ROOT)) {
  const rel = path.relative(ROOT, file).replace(/\\/g, '/');
  if (SKIP_FILES.has(rel)) continue;
  try {
    entries.push(processFile(file));
  } catch (e) {
    console.warn(`  skipped ${rel}: ${e.message}`);
  }
}

const header = [
  '// Auto-generated by tools/build-search-index.js — do not edit manually.',
  '// Run: node tools/build-search-index.js',
].join('\n');

fs.writeFileSync(OUT, `${header}\nconst INDEX = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`✓  ${entries.length} pages indexed → assets/search-index.js`);
